/**
 * One-time helper: extract classic article bodies from git history.
 * Run: node scripts/extract-classic-article-bodies.mjs
 */
import { execSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { LEGACY_NEWSLETTER_ARTICLES } from "./legacy-newsletter-articles.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");

const GIT_COMMIT = "71b44c2";
const FALLBACK_COMMIT = "9a2832c";

function fixEncoding(html) {
  return html
    .replace(/┬╖/g, "·")
    .replace(/ΓÇö/g, "—")
    .replace(/ΓåÆ/g, "→")
    .replace(/Γåô/g, "↓")
    .replace(/ΓÇô/g, "–")
    .replace(/≡ƒöù/g, "")
    .replace(/┬⌐/g, "©");
}

function stripExtras(html) {
  return html
    .replace(/<figure[\s\S]*?<\/figure>/gi, "")
    .replace(/<section class="article-help">[\s\S]*?<\/section>/g, "")
    .replace(/<section class="article-author-module">[\s\S]*?<\/section>/g, "")
    .replace(/<p class="article-signoff">[\s\S]*?<\/p>/g, "")
    .trim();
}

function extractFromOldHtml(html) {
  const parts = [];
  const intro = html.match(/<div class="article-intro">([\s\S]*?)<\/div>\s*(?:<figure|<div class="article-content")/);
  const content = html.match(/<div class="article-content">([\s\S]*?)<\/div>\s*(?:<div class="article-outro">|<\/main>|<nav class="article-nav">)/);
  const outro = html.match(/<div class="article-outro">([\s\S]*?)<\/div>\s*(?:<\/article>|<section)/);

  if (intro) parts.push(intro[1]);
  if (content) parts.push(content[1]);
  if (outro) parts.push(outro[1]);

  // story-hooks: lede inside article-main, body in sibling article-content
  if (!parts.length) {
    const lede = html.match(/<p class="article-lede">([\s\S]*?)<\/p>/);
    const standalone = html.match(/<div class="article-content">([\s\S]*?)<\/div>\s*<\/main>/);
    if (lede) parts.push(`<p class="lead">${lede[1]}</p>`);
    if (standalone) parts.push(standalone[1]);
  }

  let body = stripExtras(parts.join("\n"));
  body = fixEncoding(body);
  body = body.replace(/<h2>/g, '<h3 class="koe-beat">').replace(/<\/h2>/g, "</h3>");
  body = body.replace(/<p class="article-lede">/g, '<p class="lead">');
  return body.trim();
}

function readFromGit(href, commit) {
  try {
    return execSync(`git show ${commit}:${href}`, {
      cwd: ROOT,
      encoding: "utf8",
      maxBuffer: 10 * 1024 * 1024,
    });
  } catch {
    return null;
  }
}

const bodies = {};

for (const article of LEGACY_NEWSLETTER_ARTICLES) {
  let html = readFromGit(article.href, GIT_COMMIT);
  if (!html || !html.includes("article-content") && !html.includes("article-intro")) {
    html = readFromGit(article.href, FALLBACK_COMMIT);
  }
  if (!html) {
    console.warn(`No source for ${article.href}`);
    continue;
  }
  const body = extractFromOldHtml(html);
  bodies[article.href] = body;
  const words = body.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length;
  console.log(`${article.href}: ${words} words`);
}

const out = `/**
 * Full body HTML for classic archive articles (restored from git history).
 * Generated by scripts/extract-classic-article-bodies.mjs
 */
export const CLASSIC_ARTICLE_BODIES = ${JSON.stringify(bodies, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, "classic-article-content.mjs"), out, "utf8");
console.log("Wrote scripts/classic-article-content.mjs");
