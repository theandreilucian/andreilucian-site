export function mergeExpansions(letter) {
  const open = OPEN[letter.num] || [];
  const extra = EXPANSIONS[letter.num] || [];
  const tail = TAIL[letter.num] || [];
  const sections = [...letter.sections];
  const leadIdx = sections.findIndex((s) => s.type === "lead");
  if (leadIdx >= 0 && open.length) {
    sections.splice(leadIdx + 1, 0, ...open);
  }
  const tangibleIdx = sections.findIndex((s) => s.type === "h2" && /tangible|try this|your move|get ahead|this week|steal/i.test(s.text));
  const insertAt = tangibleIdx >= 0 ? tangibleIdx : sections.length;
  sections.splice(insertAt, 0, ...extra);
  sections.push(...tail);
  return { ...letter, sections };
}

